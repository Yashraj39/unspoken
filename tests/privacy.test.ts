import assert from 'node:assert/strict';
import { webcrypto } from 'node:crypto';
import { generateKey, maskVote, mixQuestions, sealQuestion } from '../lib/privacy';
import { freshGame, mutate, tick, view } from '../lib/game-engine';
import type { Lobby, Peer } from '../lib/game-types';
const native=globalThis.crypto;
const keys=await Promise.all(Array.from({length:4},()=>generateKey()));
const peers:Peer[]=keys.map((k,i)=>({id:`peer-${i}`,key:k.publicKey,gender:i===3?'female':'male'}));
const active=peers.map(p=>p.id);
const answers=[2,0,2,1];
const vectors=await Promise.all(peers.map((p,i)=>maskVote(keys[i].privateKey,p.id,peers,active,'round:question',answers[i],4)));
const sum=(v:number[][])=>v.reduce((a,b)=>a.map((n,i)=>(n+b[i])>>>0),[0,0,0,0]);
assert.deepEqual(sum(vectors),[1,1,2,0]);
assert(vectors.every(v=>v.some(x=>x>100000)));
await assert.rejects(()=>maskVote(keys[0].privateKey,peers[0].id,peers,active.slice(0,2),'small',0,4));
const largePeers:Peer[]=Array.from({length:50},(_,i)=>({...peers[i%4],id:`large-${i}`}));
const largeQuestion={id:'large',text:'Who would host the best party?',options:largePeers.map(p=>p.id),audience:'all' as const};
let largeBatch=await sealQuestion(largeQuestion,largePeers,'large-room');
assert.equal(Buffer.from(largeBatch,'base64').length,8192+92*50);
for(let i=0;i<50;i++){const next=await mixQuestions([largeBatch],keys[i%4].privateKey,'large-room',i===49);if(i===49)assert.deepEqual(next[0],largeQuestion);else largeBatch=next[0] as string;}
const questions=peers.map((p,i)=>({id:`q${i}`,text:`Private question number ${i}?`,options:['Yes','No'],audience:'all' as const}));
let batch=await Promise.all(questions.map(q=>sealQuestion(q,peers,'round')));
assert.equal(new Set(batch.map(x=>x.length)).size,1);
assert(!batch.some(x=>x.includes('Private question')));
for(let i=0;i<peers.length;i++)batch=await mixQuestions(batch,keys[i].privateKey,'round',i===peers.length-1) as string[];
assert.deepEqual((batch as unknown as typeof questions).map(q=>q.text).sort(),questions.map(q=>q.text).sort());
// Native Web Crypto and device-only Noble fallback must interoperate.
Object.defineProperty(globalThis,'crypto',{value:{getRandomValues:webcrypto.getRandomValues.bind(webcrypto)},configurable:true});
const fallback=await generateKey();
const fallbackPeer={id:'peer-4',key:fallback.publicKey,gender:'male' as const};
const mixedPeers=[...peers.slice(0,2),fallbackPeer];
const fallbackVector=await maskVote(fallback.privateKey,'peer-4',mixedPeers,mixedPeers.map(p=>p.id),'mixed',1,4);
Object.defineProperty(globalThis,'crypto',{value:native,configurable:true});
const mixedVectors=await Promise.all(mixedPeers.slice(0,2).map((p,i)=>maskVote(keys[i].privateKey,p.id,mixedPeers,mixedPeers.map(p=>p.id),'mixed',i,4)));
assert.deepEqual(sum([...mixedVectors,fallbackVector]),[1,2,0,0]);
const l:Lobby={host:'peer-0',players:peers.map((p,i)=>({...p,name:`Name${i}`,auth:`lobby-${i}`,anonymousAuth:`anon-${i}`,locked:true,ready:true,active:true,seen:Date.now()}))};
// A setup correction reopens everyone's choices; only the host may initiate it.
const setup=freshGame();setup.phase='CHECK';const originalRound=setup.round;
assert.throws(()=>mutate(l,setup,l.players[1],null,'reset',{},Date.now()));
mutate(l,setup,l.players[0],null,'reset',{},Date.now());
assert.equal(setup.phase,'LOBBY');assert.notEqual(setup.round,originalRound);
assert(l.players.every(p=>p.needsName&&!p.locked&&!p.ready&&p.gender===null));
assert.throws(()=>mutate(l,setup,l.players[0],null,'gender',{gender:'male'},Date.now()));
assert.throws(()=>mutate(l,setup,l.players[0],null,'name',{name:'Name1'},Date.now()));
assert.throws(()=>mutate(l,setup,l.players[0],null,'name',{name:'Bad\u0000name'},Date.now()));
assert.throws(()=>mutate(l,setup,l.players[0],null,'check',{},Date.now()));
for(let i=0;i<l.players.length;i++){
  mutate(l,setup,l.players[i],null,'name',{name:`Correct${i}`},Date.now());
  mutate(l,setup,l.players[i],null,'gender',{gender:i===3?'female':'male'},Date.now());
}
mutate(l,setup,l.players[0],null,'check',{},Date.now());
assert.equal(setup.phase,'CHECK');
const checked=view('123456',0,l,setup,l.players[0],null,Date.now());
assert.equal(checked.players?.find(p=>p.id==='peer-3')?.name,'Correct3');
assert.equal(checked.players?.find(p=>p.id==='peer-3')?.gender,'female');
assert.throws(()=>mutate(l,setup,l.players[1],null,'name',{name:'Changed'},Date.now()));
for(const p of l.players)mutate(l,setup,p,null,'ready',{},Date.now());
const g=freshGame();g.phase='CHECK';mutate(l,g,l.players[0],null,'lock',{},Date.now());
assert.equal(g.phase,'LOCK');const lockedView=view('123456',0,l,g,null,'peer-0',Date.now());assert(!lockedView.players);assert(!JSON.stringify(lockedView).includes('auth'));
assert(!('needsName' in lockedView.me));
assert.throws(()=>mutate(l,g,l.players[0],'peer-0','reset',{},Date.now()));
assert.throws(()=>mutate(l,g,l.players[0],'peer-0','name',{name:'Changed'},Date.now()));
await assert.rejects(async()=>mutate(l,g,l.players[0],'peer-0','gender',{gender:'female'},Date.now()));
g.phase='ANSWER';g.questions=[{id:'poll',text:'A private vote?',options:['A','B','C','D'],audience:'all'}];g.deadline=Date.now()+30000;
for(const p of peers)mutate(l,g,null,p.id,'commit',{question:'poll'},Date.now());assert.equal(g.phase,'TALLY');
for(let i=0;i<4;i++)mutate(l,g,null,peers[i].id,'masked',{question:'poll',vector:vectors[i]},Date.now());
assert.equal(g.phase,'RESULTS');assert.deepEqual(g.totals,[1,1,2,0]);assert.deepEqual(g.masked,{});
const publicResult=view('123456',0,l,g,null,'peer-1',Date.now());assert(!('masked' in publicResult));assert(!('commits' in publicResult));assert(!JSON.stringify(publicResult.question).match(/author|voter|uid/));
for(const p of peers)mutate(l,g,null,p.id,'next',{question:'poll'},Date.now());assert.equal(g.phase,'COMPLETE');assert.deepEqual(g.questions,[]);assert.deepEqual(g.masked,{});
mutate(l,g,null,'peer-3','leave',{},Date.now());assert.equal(l.players.length,3);
mutate(l,g,null,'peer-0','lobby',{},Date.now());assert.equal(g.phase,'LOBBY');assert(l.players.every(p=>!p.locked&&!p.ready));
const small=freshGame();small.phase='ANSWER';small.peers=peers;small.questions=[{id:'small',text:'A private vote?',options:['A','B'],audience:'all'}];small.deadline=Date.now()-1;small.commits={'peer-0':true};tick(l,small,Date.now());assert.equal(small.phase,'RESULTS');assert.equal(small.totals,null);assert.deepEqual(small.masked,{});
console.log('Passed: aggregate masking, equal padded envelopes, client shuffle, native/fallback interoperability, host-only setup reset, name confirmation, phase locks, private views, cleanup and low-response withholding.');
